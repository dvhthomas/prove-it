def main() -> int:
    if len(sys.argv) != 2:
        print("usage: build_site.py <run-dir>", file=sys.stderr)
        return 2

    run_dir = Path(sys.argv[1]).expanduser().resolve()
    meta_path = run_dir / "metadata.json"

    if not meta_path.exists():
        print(f"missing: {meta_path}", file=sys.stderr)
        return 1

    meta = json.loads(meta_path.read_text())
    (run_dir / "index.html").write_text(render(meta))
    (run_dir / "style.css").write_text(CSS)
    print(f"wrote: {run_dir / 'index.html'}")
    print(f"wrote: {run_dir / 'style.css'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
