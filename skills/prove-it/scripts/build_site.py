#!/usr/bin/env python3
"""Build a self-contained static evidence site from metadata.json.

Usage: build_site.py <run-dir>

Reads <run-dir>/metadata.json and writes:
  <run-dir>/index.html
  <run-dir>/style.css

The site opens directly via file:// — no server, no CDN, no JS framework.
Assets referenced by metadata.json (videos, screenshots) must already exist
in <run-dir>/assets/<scenario-slug>/.
"""

from __future__ import annotations

import html
import json
import sys
from pathlib import Path

STATUS_LABELS = {
    "pass": ("pass", "Pass"),
    "needs-attention": ("warn", "Needs attention"),
    "fail": ("fail", "Fail"),
}


def render(meta: dict) -> str:
    run_id = html.escape(str(meta.get("run_id", "unknown")))
    app = meta.get("app", {}) or {}
    env = meta.get("environment", {}) or {}
    scenarios = meta.get("scenarios", []) or []

    app_name = html.escape(str(app.get("name", "app")))
    app_version = html.escape(str(app.get("version", "")))
    app_target = html.escape(str(app.get("url_or_command", "")))
    env_os = html.escape(str(env.get("os", "")))
    env_browser = html.escape(str(env.get("browser", "")))

    counts = {"pass": 0, "needs-attention": 0, "fail": 0}
    for s in scenarios:
        st = s.get("status", "pass")
        if st in counts:
            counts[st] += 1

    overall_class, overall_label = "pass", "All scenarios passed"
    if counts["fail"]:
        overall_class, overall_label = "fail", f'{counts["fail"]} scenario(s) failed'
    elif counts["needs-attention"]:
        overall_class, overall_label = "warn", f'{counts["needs-attention"]} scenario(s) need attention'

    scenario_blocks = []
    for s in scenarios:
        slug = html.escape(str(s.get("slug", "scenario")))
        title = html.escape(str(s.get("title", slug)))
        narrative = html.escape(str(s.get("narrative", "")))
        notes = html.escape(str(s.get("notes", "")))
        duration = s.get("duration_seconds")
        duration_text = f"{int(duration)}s" if isinstance(duration, (int, float)) else ""
        status = s.get("status", "pass")
        status_class, status_label = STATUS_LABELS.get(status, ("pass", html.escape(status)))

        video_html = ""
        video_path = s.get("video")
        if video_path:
            v = html.escape(str(video_path))
            video_html = (
                f'<video controls preload="metadata" src="{v}">'
                f'Your browser cannot play this video. Open <a href="{v}">{v}</a> directly.'
                f"</video>"
            )

        shots_html = []
        for shot in s.get("screenshots", []) or []:
            f = html.escape(str(shot.get("file", "")))
            cap = html.escape(str(shot.get("caption", "")))
            if not f:
                continue
            shots_html.append(
                f'<figure class="shot">'
                f'<a href="{f}" target="_blank"><img src="{f}" alt="{cap}" loading="lazy"></a>'
                f'<figcaption>{cap}</figcaption>'
                f"</figure>"
            )
        shots_block = "\n".join(shots_html) if shots_html else '<p class="muted">No screenshots captured.</p>'

        notes_block = f'<p class="notes"><strong>Notes:</strong> {notes}</p>' if notes else ""
        duration_block = f'<span class="duration">{duration_text}</span>' if duration_text else ""

        scenario_blocks.append(
            f"""
<section class="scenario" id="{slug}">
  <header class="scenario-head">
    <span class="status status-{status_class}">{status_label}</span>
    <h2>{title}</h2>
    {duration_block}
  </header>
  <p class="narrative">{narrative}</p>
  {video_html}
  <div class="shots">
    {shots_block}
  </div>
  {notes_block}
</section>
"""
        )

    body_scenarios = "\n".join(scenario_blocks) if scenario_blocks else '<p class="muted">No scenarios recorded.</p>'

    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>prove-it · {app_name} · {run_id}</title>
<link rel="stylesheet" href="style.css">
</head>
<body>
<header class="page-head">
  <h1>prove-it</h1>
  <p class="run-meta">
    <strong>{app_name}</strong>
    <span class="muted">{app_version}</span>
    · run <code>{run_id}</code>
  </p>
  <p class="env muted">{env_os} · {env_browser} · target <code>{app_target}</code></p>
  <p class="overall status status-{overall_class}">{overall_label}</p>
  <ul class="summary">
    <li><span class="dot dot-pass"></span> {counts['pass']} passed</li>
    <li><span class="dot dot-warn"></span> {counts['needs-attention']} need attention</li>
    <li><span class="dot dot-fail"></span> {counts['fail']} failed</li>
  </ul>
</header>
<main>
{body_scenarios}
</main>
<footer class="page-foot muted">
  Generated by the <a href="https://github.com/dvhthomas/prove-it">prove-it</a> skill.
  Open this page directly via <code>file://</code> — no server required.
</footer>
</body>
</html>
"""


